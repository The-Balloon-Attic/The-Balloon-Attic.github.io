#!/usr/bin/env node
/**
 * Generates the gallery's image index by scanning the category folders on disk.
 *
 * This is the only piece of "build tooling" this static site has, and it exists
 * for one reason: GitHub Pages can't list a directory's contents at runtime, so
 * the front end needs an index of what images exist. Rather than asking anyone
 * to hand-maintain that index, this script (re)builds it automatically.
 *
 * It writes two files with the same data:
 *   - assets/images/manifest.js    <script>-loadable, sets window.__GALLERY_MANIFEST__.
 *                                   This is what index.html actually loads. Because
 *                                   it's a plain <script src>, not a fetch()'d JSON
 *                                   file, it works when index.html is opened directly
 *                                   via file:// — no local server required — since
 *                                   Chrome (and other browsers) block fetch()/XHR of
 *                                   file:// URLs but not <script src> of them.
 *   - assets/images/manifest.json  Same data as plain JSON, kept for readability/
 *                                   tooling. main.js falls back to fetching this if
 *                                   manifest.js somehow didn't load, but normal page
 *                                   loads never need to.
 *
 * Usage:
 *   node scripts/generate-manifest.js
 *
 * The GitHub Action in .github/workflows/update-gallery-manifest.yml runs this
 * on every push that touches assets/images/**, so in practice nobody needs to
 * run it by hand — dropping a photo into a category folder and pushing is
 * enough. It's kept runnable manually too, for local preview before pushing.
 */

const fs = require('fs');
const path = require('path');

// Keep this list in sync with the folder-balloon buttons in index.html
// (data-category attributes). Order here doesn't matter — display order is
// controlled by the HTML/CSS, not by this script.
const CATEGORIES = [
    'birthdays',
    'christenings',
    'special-days',
    'events',
    'weddings',
    'easter',
    'christmas',
    'halloween',
];

const ALLOWED_EXTENSIONS = new Set(['jpg', 'jpeg', 'png', 'webp', 'gif', 'avif']);

const IMAGES_DIR = path.join(__dirname, '..', 'assets', 'images');
const MANIFEST_JSON_PATH = path.join(IMAGES_DIR, 'manifest.json');
const MANIFEST_JS_PATH = path.join(IMAGES_DIR, 'manifest.js');

function isImageFile(filename) {
    const ext = filename.split('.').pop()?.toLowerCase();
    return !!ext && ALLOWED_EXTENSIONS.has(ext);
}

// Lists image files directly inside `dir` (non-recursive), sorted alphabetically
// for stable, diff-friendly output. Display ordering (featured images, newest
// first, etc.) is applied client-side in scripts/main.js.
function listImages(dir) {
    if (!fs.existsSync(dir)) return [];
    return fs
        .readdirSync(dir, { withFileTypes: true })
        .filter((entry) => entry.isFile() && isImageFile(entry.name))
        .map((entry) => entry.name)
        .sort((a, b) => a.localeCompare(b));
}

function generateManifest() {
    const manifest = {};

    for (const category of CATEGORIES) {
        manifest[category] = listImages(path.join(IMAGES_DIR, category));
    }

    // Images that still live directly in assets/images/ (not yet sorted into a
    // category folder). Nothing is ever silently dropped — recorded here so
    // it's easy to spot photos still waiting to be filed away, even though the
    // front end no longer displays an "uncategorized" bucket.
    manifest.uncategorized = listImages(IMAGES_DIR);

    return manifest;
}

function main() {
    const manifest = generateManifest();
    const json = `${JSON.stringify(manifest, null, 2)}\n`;

    fs.writeFileSync(MANIFEST_JSON_PATH, json, 'utf8');
    fs.writeFileSync(
        MANIFEST_JS_PATH,
        `// Auto-generated by scripts/generate-manifest.js — do not edit by hand.\n` +
        `// Loaded as a plain <script>, not fetched, so the gallery also works when\n` +
        `// index.html is opened directly (file://) with no local server.\n` +
        `window.__GALLERY_MANIFEST__ = ${json.trim()};\n`,
        'utf8'
    );

    const totalCategorized = CATEGORIES.reduce((sum, cat) => sum + manifest[cat].length, 0);
    console.log('Gallery manifest updated:');
    for (const category of CATEGORIES) {
        console.log(`  ${category.padEnd(14)} ${manifest[category].length}`);
    }
    console.log(`  ${'uncategorized'.padEnd(14)} ${manifest.uncategorized.length}`);
    console.log(`  ${'total'.padEnd(14)} ${totalCategorized + manifest.uncategorized.length}`);
}

main();
